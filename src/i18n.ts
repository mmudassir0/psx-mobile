export const tr = (text: string, lang: Lang) => (lang === 'ur' ? (UR[text] ?? text) : text);

// the language for tt(): set by useLang() in the screens that use it, so sub-components can translate without their own hook
let current: Lang = 'en';
langPref.get().then((l) => (current = l));
/** Translate with the language last seen by useLang(). */
export const tt = (text: string) => tr(text, current);
/** Subscribe a screen to the language (re-renders it, and its children, on a change). */
export function useLang(): Lang {
  const l = langPref.use();
  current = l;
  return l;
}
export const isRtl = (lang: Lang) => lang === 'ur';

